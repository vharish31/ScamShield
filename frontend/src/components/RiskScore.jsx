import React from 'react';
import { getRiskMeta, formatDateTime } from '../utils/scamHelpers';
import RiskBadge from './RiskBadge';

export default function RiskScore({
  score = 0,
  level = 'LOW',
  createdAt,
  isHeuristic = true,
  disclaimer,
}) {
  const meta = getRiskMeta(level);
  const clamped = Math.min(100, Math.max(0, Number(score) || 0));

  const shortExplanation =
    clamped >= 75
      ? 'High concentration of coercive, financial, or impersonation indicators detected.'
      : clamped >= 50
      ? 'Notable scam markers found; independent verification is strongly advised.'
      : clamped >= 25
      ? 'Moderate urgency or unusual cues observed; proceed cautiously.'
      : 'Conversation appears safe with minimal or no manipulation triggers.';

  return (
    <div className="ss-card p-4 text-center h-100 d-flex flex-column justify-content-between">
      <div>
        <span
          className="text-sec text-uppercase fw-bold d-block"
          style={{ fontSize: '0.73rem', letterSpacing: '0.06em' }}
        >
          AI Risk Score
        </span>

        <div
          className="ss-risk-gauge my-4"
          style={{
            background: `conic-gradient(${meta.color} ${clamped * 3.6}deg, var(--ss-border) 0deg)`,
          }}
          role="img"
          aria-label={`Risk score ${clamped} out of 100 (${meta.label})`}
        >
          <div className="ss-risk-gauge-inner">
            <span
              className="font-mono fw-bold"
              style={{ fontSize: '2.5rem', color: meta.color, lineHeight: 1 }}
            >
              {clamped}
            </span>
            <span className="text-sec small fw-semibold mt-1">/ 100</span>
          </div>
        </div>

        <div className="mb-3">
          <RiskBadge level={level} className="px-4 py-2 fs-6" />
        </div>

        <p className="text-sec small mb-3 px-2">{shortExplanation}</p>

        {createdAt && (
          <div className="text-mut mb-3" style={{ fontSize: '0.75rem' }}>
            <i className="bi bi-clock me-1" />
            Evaluated: {formatDateTime(createdAt)}
          </div>
        )}
      </div>

      {/* Explicit Heuristic / Indicator Disclaimer */}
      <div
        className="p-3 rounded-3 border text-start"
        style={{ backgroundColor: 'var(--ss-surface-muted)' }}
      >
        <div className="d-flex align-items-center justify-content-between mb-1">
          <span className="badge bg-primary-light text-primary-brand" style={{ fontSize: '0.67rem' }}>
            {isHeuristic ? 'HEURISTIC INDICATOR' : 'ML + HEURISTIC'}
          </span>
        </div>
        <p className="text-sec mb-0" style={{ fontSize: '0.74rem', lineHeight: 1.45 }}>
          {disclaimer ||
            'This score is an indicator generated by the detection system, not proof of fraud or a calibrated probability. Always verify suspicious callers independently.'}
        </p>
      </div>
    </div>
  );
}

